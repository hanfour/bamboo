# Writes Config/Version.xcconfig with MARKETING_VERSION taken from the
# nearest v* release tag, so the version an app reports to the controller
# (CFBundleShortVersionString -> clientVersion) follows the release and is
# not edited by hand. project.yml runs this before every `xcodegen generate`.
#
# A build between tags reports the last tag; CURRENT_PROJECT_VERSION is
# what tells such builds apart. The value must be three dotted integers, as
# iOS requires, so anything else (no tag, a checkout without tags, git
# missing) falls back to 0.0.0 and says so.

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

OUT="Config/Version.xcconfig"
version=""
if tag="$(git describe --tags --abbrev=0 --match 'v[0-9]*' 2>/dev/null)"; then
    version="${tag#v}"
fi
if [[ ! "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "gen-version-xcconfig: no usable v* tag (got '${version:-none}'); using 0.0.0" >&2
    version="0.0.0"
fi

mkdir -p Config
printf '// Generated by scripts/gen-version-xcconfig.sh; do not edit or commit.\nMARKETING_VERSION = %s\n' "$version" > "$OUT"
echo "MARKETING_VERSION=$version"
